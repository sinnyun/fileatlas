const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');

module.exports=async({call,payload,step,delay,profile})=>{
  const data=JSON.parse(fs.readFileSync(path.join(profile,'workcrate-scenario.json'),'utf8'));
  const project_id=data.projects[0].id,board_id=data.ids[0];
  const invoke=async(tool,args={})=>payload(await call(tool,args));
  const ready=async screen=>{for(let i=0;i<120;i++){const state=await invoke('workcrate-ui.state');if(state.ui?.screen===screen&&!state.ui.busy)return state;await delay(200);}throw Error(`${screen} did not settle`);};
  const pointer=async(action,x,y)=>{for(let i=0;;i++){try{return await invoke('control_ui',{action,value:`${x},${y}`});}catch(error){if(i>=30||!String(error).includes('pointer request is still pending'))throw error;await delay(100);}}};
  const click=async(x,y)=>{await pointer('pointer_down',x,y);await delay(100);await pointer('pointer_up',x,y);await delay(300);};
  const bounds=async()=>{for(let i=0;i<60;i++){const ui=await invoke('get_ui_state');const value=ui.panel_instances.find(p=>p.id.startsWith('workcrate/overview@'))?.client_bounds;if(value)return value.split(',').map(Number);await delay(100);}throw Error('Panel has no painted bounds');};
  await invoke('workcrate-ui.navigate');await ready('projects');
  let [x,y]=await bounds();
  const ordered=[...data.projects].sort((a,b)=>b.created_at-a.created_at||a.name.localeCompare(b.name));
  const column=ordered.findIndex(p=>p.id===project_id);
  await click(x+24+384*column+344,y+134);
  await step({tool:'workcrate-ui.state',capture:'project-menu'});
  await click(x+24+384*column+140,y+260);
  let state=await ready('pages');assert.equal(state.ui.project_id,project_id);
  [x,y]=await bounds();
  await click(x+40,y+134);await click(x+788,y+134);
  state=await invoke('workcrate-ui.state');assert.equal(state.ui.selected_pages.length,2);
  await step({tool:'workcrate-ui.state',capture:'pages-selected'});
  await invoke('workcrate-ui.navigate',{project_id,board_id});await ready('editor');await delay(700);
  [x,y]=await bounds();
  const manifest=path.join(profile,'workcrate/projects',project_id,'boards',`${board_id}.json`);
  const before=JSON.parse(fs.readFileSync(manifest,'utf8'));
  await pointer('pointer_down',x+420,y+440);await pointer('pointer_drag',x+415,y+435);await pointer('pointer_up',x+415,y+435);
  await delay(300);state=await ready('editor');
  const after=JSON.parse(fs.readFileSync(manifest,'utf8'));
  assert(state.ui.selected_image,'canvas click should select an image');
  assert.notDeepEqual(after.source.spreads,before.source.spreads,'drag must persist a DesignCraft transform');
  await step({tool:'workcrate-ui.state',capture:'editor-selected'});
  const artifacts=path.join(profile,'artifacts');
  await step({tool:'workcrate-ui.export_pages',arguments:{project_id,board_ids:data.ids,path:path.join(artifacts,'all-pages.pdf'),format:'pdf',confirm:true}});
  for(const ext of ['png','jpg'])await step({tool:'workcrate-ui.export_pages',arguments:{project_id,board_ids:[board_id],path:path.join(artifacts,`first-page.${ext}`),format:'image',confirm:true}});
  await step({tool:'resize_window',arguments:{width:1280,height:960},wait_ms:1000,capture:'editor-small'});
  await step({tool:'resize_window',arguments:{width:3286,height:1831},wait_ms:500});
  fs.writeFileSync(path.join(profile,'interactions.json'),JSON.stringify({checks:['project menu','cover navigation','two page selection','canvas hit selection','DesignCraft drag transform','A3 PDF/PNG/JPEG','small window screenshot'],selected:state.ui.selected_image},null,2));
  console.log('WorkCrate native MCP interactions passed');
};
