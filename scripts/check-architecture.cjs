// Architecture guard: freezes cross-plugin coupling, UI-stack ownership and
// unwrap/expect debt at recorded baselines. Ratchets only shrink.
// Rules and tokens: docs/engineering-governance.md (A1-A5).
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const cratesDir = path.join(root, 'crates');
const baselinePath = path.join(root, '.governance', 'architecture-baseline.json');
const update = process.argv.includes('--update-baseline');

function rsFiles(dir) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...rsFiles(file));
    else if (entry.name.endsWith('.rs')) out.push(file);
  }
  return out;
}

const crateNames = fs
  .readdirSync(cratesDir, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const workspaceText = fs.readFileSync(path.join(root, 'Cargo.toml'), 'utf8');
const members = [...workspaceText.matchAll(/"(crates\/[a-z0-9-]+)"/g)].map((m) =>
  m[1].slice('crates/'.length)
);

const failures = [];
const warnings = [];

// A1: workspace membership <-> directory truth.
for (const name of crateNames) {
  const hasManifest = fs.existsSync(path.join(cratesDir, name, 'Cargo.toml'));
  if (!hasManifest) {
    warnings.push(`A1 orphan directory (no Cargo.toml, untracked): crates/${name}`);
    continue;
  }
  if (!members.includes(name)) failures.push(`A1 crates/${name} has Cargo.toml but is not a workspace member`);
}
for (const name of members) {
  if (!crateNames.includes(name)) failures.push(`A1 member crates/${name} does not exist on disk`);
  else if (!rsFiles(path.join(cratesDir, name, 'src')).length)
    failures.push(`A1 member crates/${name} has no Rust sources`);
}

// A2: cross-plugin import edges (fileatlas_plugin_b:: seen from crate a).
const edges = new Map(); // "a -> b" -> files
for (const name of crateNames) {
  for (const file of rsFiles(path.join(cratesDir, name, 'src'))) {
    const text = fs.readFileSync(file, 'utf8');
    for (const m of text.matchAll(/fileatlas_plugin_([a-z0-9_]+)::/g)) {
      const target = `fileatlas-plugin-${m[1].replaceAll('_', '-')}`;
      if (target === name || !crateNames.includes(target)) continue;
      const key = `${name} -> ${target}`;
      if (!edges.has(key)) edges.set(key, new Set());
      edges.get(key).add(path.relative(root, file).replaceAll('\\', '/'));
    }
  }
}

// A3: crates that link the gpui UI stack.
const uiStack = [];
for (const name of crateNames) {
  const manifest = path.join(cratesDir, name, 'Cargo.toml');
  if (!fs.existsSync(manifest)) continue;
  const text = fs.readFileSync(manifest, 'utf8');
  if (/^(gpui|gpui-kit|gpui-pre|winit|eframe)\b.*=/m.test(text)) uiStack.push(name);
}

// A4: unwrap/expect debt per crate (src only; includes #[cfg(test)] modules).
const debt = {};
for (const name of crateNames) {
  let count = 0;
  for (const file of rsFiles(path.join(cratesDir, name, 'src'))) {
    const text = fs.readFileSync(file, 'utf8');
    count += (text.match(/\.unwrap\(\)/g) || []).length + (text.match(/\.expect\(/g) || []).length;
  }
  if (fs.existsSync(path.join(cratesDir, name, 'Cargo.toml'))) debt[name] = count;
}

// A5: deny coverage must match zero-debt product crates. The deny lives as a
// crate attribute in lib.rs because [lints] workspace=true forbids local keys.
function crateFacts(name) {
  const manifest = path.join(cratesDir, name, 'Cargo.toml');
  const lib = path.join(cratesDir, name, 'src', 'lib.rs');
  if (!fs.existsSync(manifest)) return null;
  const manifestText = fs.readFileSync(manifest, 'utf8');
  const libText = fs.existsSync(lib) ? fs.readFileSync(lib, 'utf8') : '';
  return {
    workspaceLints: /\[lints\][^[]*workspace\s*=\s*true/.test(manifestText),
    deny: /deny\(\s*clippy::(unwrap_used|expect_used)/.test(libText),
  };
}

if (update) {
  fs.mkdirSync(path.dirname(baselinePath), { recursive: true });
  const baseline = {
    comment: 'Generated by scripts/check-architecture.cjs --update-baseline. Shrink-only ratchet; review diffs before committing.',
    pluginEdges: [...edges.keys()].sort(),
    uiStackCrates: uiStack.sort(),
    unwrapExpectDebt: debt,
    denyCrates: crateNames.filter((name) => crateFacts(name)?.deny).sort(),
    workspaceLintsCrates: crateNames.filter((name) => crateFacts(name)?.workspaceLints).sort(),
  };
  fs.writeFileSync(baselinePath, JSON.stringify(baseline, null, 2) + '\n');
  console.log(`baseline written: ${path.relative(root, baselinePath)} (edges=${baseline.pluginEdges.length}, debt total=${Object.values(debt).reduce((a, b) => a + b, 0)})`);
  process.exitCode = 0;
} else {
  if (!fs.existsSync(baselinePath)) {
    console.error('missing .governance/architecture-baseline.json; run: node scripts/check-architecture.cjs --update-baseline');
    process.exitCode = 1;
  } else {
    const baseline = JSON.parse(fs.readFileSync(baselinePath, 'utf8'));
    const allowedEdges = new Set(baseline.pluginEdges);
    for (const key of [...edges.keys()].sort()) {
      if (!allowedEdges.has(key))
        failures.push(`A2 NEW cross-plugin edge ${key} (first seen: ${[...edges.get(key)][0]})`);
    }
    const allowedUi = new Set(baseline.uiStackCrates);
    for (const name of uiStack)
      if (!allowedUi.has(name)) failures.push(`A3 NEW ui-stack consumer: crates/${name}`);
    for (const name of allowedUi)
      if (!uiStack.includes(name) && debt[name] !== undefined)
        warnings.push(`A3 ui-stack entry no longer links gpui: crates/${name} (shrink the baseline)`);

    for (const [name, count] of Object.entries(debt)) {
      const recorded = baseline.unwrapExpectDebt[name];
      if (recorded === undefined) failures.push(`A4 unrecorded crate debt baseline for ${name} (${count}); update baseline`);
      else if (count > recorded)
        failures.push(`A4 debt grew in ${name}: ${recorded} -> ${count} (.unwrap()/.expect( in src)`);
    }

    const denySet = new Set(baseline.denyCrates);
    const wsLintSet = new Set(baseline.workspaceLintsCrates);
    for (const name of crateNames) {
      const facts = crateFacts(name);
      if (!facts) continue;
      if (denySet.has(name) && !facts.deny) failures.push(`A5 ${name}: baseline expects unwrap/expect deny, crate attribute lost it`);
      if (!denySet.has(name) && facts.deny) failures.push(`A5 ${name}: deny added but baseline not updated`);
      if (facts.deny && debt[name] > 0) failures.push(`A5 ${name}: deny active but debt is ${debt[name]}`);
      if (wsLintSet.has(name) && !facts.workspaceLints) failures.push(`A5 ${name}: [lints] workspace=true removed`);
      if (!wsLintSet.has(name) && facts.workspaceLints) failures.push(`A5 ${name}: [lints] workspace=true added; update baseline`);
    }

    if (warnings.length) console.warn(warnings.join('\n'));
    if (failures.length) {
      console.error(failures.join('\n'));
      process.exitCode = 1;
    } else {
      console.log(
        `architecture guard: passed (edges=${baseline.pluginEdges.length}, debt=${Object.values(debt).reduce((a, b) => a + b, 0)}, ui crates=${uiStack.length})`
      );
    }
  }
}
