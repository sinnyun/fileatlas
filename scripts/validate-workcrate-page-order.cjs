const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const net=require('node:net');
module.exports=async({step,call,payload,delay,profile})=>{
  const invoke=async(tool,args={},extra={})=>(await step({tool,arguments:args,wait_ms:100,...extra})).result;
  const read=async(ids=[])=>payload(await call('workcrate-ui.state',{control_ids:ids}));
  const until=async(test,label,ids=[])=>{let s;for(let i=0;i<120;i++){s=await read(ids);if(s?.ui&&test(s))return s;await delay(150);}await invoke('workcrate-ui.state',{}, {capture:'failed-order'});throw Error(`${label}: ${JSON.stringify(s)}`);};
  const ready=()=>until(s=>!s.ui.busy&&!s.ui.canvas.busy&&!s.ui.field_saves.length&&!s.ui.preview_pending&&s.ui.previews_ready===s.ui.page_count,'ready');
  const ui=async(action,value)=>{for(let i=0;i<40;i++){try{return await invoke('control_ui',{action,value});}catch(e){if(!String(e).includes('still pending'))throw e;await delay(100);}}throw Error('input queue busy');};
  const point=async id=>{const s=await until(s=>s.controls[id],id,[id]);const[x,y,w,h]=s.controls[id].split(',').map(Number);return[x+w/2,y+h/2];};
  const click=async id=>{const p=await point(id);await ui('pointer_down',p.join(','));await ui('pointer_up',p.join(','));};
  const drag=async(from,to)=>{const a=await point(from),b=await point(to);await ui('pointer_down',a.join(','));for(let i=1;i<=12;i++)await ui('pointer_drag',`${a[0]+(b[0]-a[0])*i/12},${a[1]+(b[1]-a[1])*i/12}`);await ui('pointer_up',b.join(','));};
  const port=await new Promise(resolve=>{const s=net.createServer();s.listen(0,'127.0.0.1',()=>{const p=s.address().port;s.close(()=>resolve(p));});});
  const directory=path.join(profile,'documents');fs.mkdirSync(directory,{recursive:true});
  await invoke('workcrate-ui.configure_vectorcraft',{executable:'C:\\Program Files\\VectorCraft\\vectorcraft.exe',port});
  const created=await invoke('workcrate-ui.manage_project',{action:'create',name:'页面排序验证',directory});
  const project_id=created.project.id,A=created.boards[0].id;assert.equal(created.boards[0].title,'页面01');
  const B=(await invoke('workcrate-ui.create_page',{project_id})).board_id;
  const C=(await invoke('workcrate-ui.create_page',{project_id})).board_id;
  const originals={};
  for(const [board_id,material] of [[A,'物料甲'],[B,'物料乙'],[C,'物料丙']]){
    await invoke('workcrate-ui.open_board',{project_id,board_id});await ready();
    await invoke('workcrate-ui.update_page',{project_id,board_id,info:{material_category:'分类',material,size:'20 cm',quantity:'1 套',extra:{工艺:'覆膜'}}});await ready();
    originals[board_id]=await invoke('workcrate-ui.header_state');
  }
  const order=s=>s.ui.boards.map(b=>b.id);
  const assertTitles=s=>s.ui.boards.forEach((b,i)=>{assert.equal(b.title,`页面${String(i+1).padStart(2,'0')}`);assert.equal(b.index,i);});
  await invoke('workcrate-ui.navigate',{project_id});await ready();assertTitles(await read());
  await click(`page-up-${C}`);
  await until(s=>!s.ui.busy&&JSON.stringify(order(s))===JSON.stringify([A,C,B]),'matrix up');await ready();
  await drag(`page-drag-${A}`,`page-drag-${B}`);
  await until(s=>!s.ui.busy&&JSON.stringify(order(s))===JSON.stringify([C,B,A]),'matrix drag');await ready();
  await invoke('workcrate-ui.state',{}, {capture:'page-order-matrix'});
  await click(`open-page-${B}`);
  await until(s=>s.ui.screen==='editor'&&s.ui.canvas.state?.board_id===B&&!s.ui.canvas.busy,'editor opened');await ready();
  const opened=await read(),rect=opened.ui.canvas.state.artboard;
  const artwork=await invoke('workcrate-ui.canvas_create_text',{x:rect.x+100,y:rect.y+200,text:'排序保持此文字',size:24,confirm:true});
  await until(s=>s.ui.canvas.state?.revision===artwork.canvas.revision&&!s.ui.canvas.busy,'artwork reflected');await ready();
  const warm=await read(),warmHeader=await invoke('workcrate-ui.header_state');
  assert.ok(warm.ui.canvas.state.selection.length);
  await click(`page-up-${B}`);
  await until(s=>{assert.equal(s.ui.canvas.state?.session_id,warm.ui.canvas.state.session_id,'canvas remains present during save');return !s.ui.busy&&JSON.stringify(order(s))===JSON.stringify([B,C,A]);},'rail up');await ready();
  const moved=await read(),movedHeader=await invoke('workcrate-ui.header_state');
  assert.equal(moved.ui.board_id,B,'selection follows stable identity');
  assert.equal(moved.ui.canvas.state.session_id,warm.ui.canvas.state.session_id,'reorder keeps native connection');
  assert.equal(moved.ui.reloads,warm.ui.reloads,'reorder does not reload the whole catalogue');
  assert.deepEqual(moved.ui.canvas.state.selection,warm.ui.canvas.state.selection,'canvas selection stays');
  assert.equal(moved.ui.canvas.state.tool,warm.ui.canvas.state.tool,'canvas tool stays');
  assert.equal(movedHeader.previews[`${A}@1600`],warmHeader.previews[`${A}@1600`],'unmoved page keeps PNG');
  assert.notEqual(movedHeader.previews[`${B}@1600`],warmHeader.previews[`${B}@1600`]);
  await drag(`page-drag-${A}`,`rail-${B}`);
  await until(s=>!s.ui.busy&&JSON.stringify(order(s))===JSON.stringify([A,B,C]),'rail drag');await ready();
  const dragged=await read();assert.equal(dragged.ui.canvas.state.session_id,warm.ui.canvas.state.session_id);assert.equal(dragged.ui.reloads,warm.ui.reloads);
  const infoState=await read(['page-auto-title','field-title','field-physical']);
  assert.ok(!infoState.controls['page-auto-title']);assert.ok(!infoState.controls['field-title']);assert.ok(!infoState.controls['field-physical']);
  await invoke('workcrate-ui.state',{}, {capture:'page-order-editor'});
  await step({tool:'workcrate-ui.reorder_pages',arguments:{project_id,board_ids:[A,A,C]},expect_error:'排序包含重复页面'});
  await step({tool:'workcrate-ui.update_page',arguments:{project_id,board_id:B,info:{size_label:'A3'}},expect_error:'仅支持修改物料内容'});
  const apiBefore=await read();
  await invoke('workcrate-ui.reorder_pages',{project_id,board_ids:[C,A,B]});
  await until(s=>JSON.stringify(order(s))===JSON.stringify([C,A,B])&&!s.ui.busy,'MCP order patch');await ready();
  const apiAfter=await read();assert.equal(apiAfter.ui.reloads,apiBefore.ui.reloads);assert.equal(apiAfter.ui.canvas.state.session_id,apiBefore.ui.canvas.state.session_id);
  const refreshed=await invoke('workcrate-ui.refresh_project',{project_id});
  assert.deepEqual(refreshed.boards.map(b=>b.id),[C,A,B]);
  refreshed.boards.forEach((b,i)=>assert.equal(b.title,`页面${String(i+1).padStart(2,'0')}`));
  for(const [i,board_id] of [C,A,B].entries()){
    await invoke('workcrate-ui.open_board',{project_id,board_id});await ready();
    const current=await invoke('workcrate-ui.header_state'),old=originals[board_id];
    assert.equal(current.nodes.page_number.text,String(i+1).padStart(2,'0'));
    for(const role of Object.keys(old.nodes))assert.equal(current.nodes[role].id,old.nodes[role].id);
    assert.deepEqual(current.nodes.details,old.nodes.details,'material values and right text remain attached to original page');
    assert.deepEqual(current.furniture,old.furniture,'native reorder does not move or rebuild furniture');
    assertTitles(await read());
  }
  const D=(await invoke('workcrate-ui.create_page',{project_id})).board_id;await ready();
  const saved=await invoke('workcrate-ui.refresh_project',{project_id});assert.deepEqual(saved.boards.map(b=>b.id),[C,A,B,D]);assert.equal(saved.boards[3].title,'页面04');
  await invoke('workcrate-ui.open_board',{project_id,board_id:D});await ready();
  const geometry=(await invoke('workcrate-ui.header_state')).artboards;
  for(let i=0;i<geometry.length;i++)for(let j=i+1;j<geometry.length;j++){
    const a=geometry[i],b=geometry[j];
    assert.ok(a.x+a.width<=b.x||b.x+b.width<=a.x||a.y+a.height<=b.y||b.y+b.height<=a.y,'new page after reorder must not overlap existing artboards');
  }
  await invoke('workcrate-ui.navigate',{project_id});await ready();
  await until(s=>s.ui.screen==='pages'&&!s.ui.canvas.state&&!s.ui.busy&&s.ui.message==='操作完成','page list settled');
  const quiet=await ready();await delay(3500);assert.equal((await read()).ui.reloads,quiet.ui.reloads);
  await invoke('material-theme.generate',{seed:'#7c3aed',variant:'tonal-spot',contrast:0,apply:true});
  await invoke('workcrate-ui.open_board',{project_id,board_id:C});await ready();
  await ui('pointer_move',(await point(`page-down-${C}`)).join(','));
  await invoke('workcrate-ui.state',{}, {capture:'page-order-accent-hover'});
  await click('field-material');await click('field-edit-input');
  await invoke('workcrate-ui.state',{}, {capture:'page-order-focus-disabled'});
  await click('field-edit-cancel');
  const ink=await invoke('workcrate-ui.header_state');
  for(const node of Object.values(ink.nodes))assert.equal(node.summary.fill,'#000000');
  await invoke('resize_window',{width:1600,height:1100});await invoke('workcrate-ui.state',{}, {capture:'page-order-small-window'});await invoke('resize_window',{width:3286,height:1831});
  fs.writeFileSync(path.join(profile,'page-order-summary.json'),JSON.stringify({passed:true,project_id,order:[C,A,B,D],checks:['matrix up','matrix drag','rail up','rail drag','same CLI session across reorder','no whole-catalogue reload','unaffected PNG retained','selection preserved','native reorder/reopen','numeric material label','automatic titles','removed info editors','new page04 without overlap','changed accent and focused draft','stable text ids and artwork','invalid permutation rejected','quiet state']},null,2));
};
