// Same-process GPUI clicks and text input, isolated database fixtures only.
// Never reads/writes the OS clipboard or injects OS input.
const assert = require('node:assert/strict');
module.exports = async ({ step, delay }) => {
  const invoke = async (tool, args = {}, wait_ms = 0) => (await step({ tool, arguments: args, wait_ms })).result;
  const quote = '好的设计应该让复杂的东西变简单。\n在快速记录与深度整理之间找到平衡。';
  const first = await invoke('add_clipboard_text', { content: quote, favorite: true });
  const link = await invoke('add_clipboard_text', { content: 'https://github.com/EcoPasteHub/EcoPaste' });
  const code = await invoke('add_clipboard_text', { content: '{"theme": "dark", "clipboard": true}' });
  await invoke('add_clipboard_text', { content: '会议重点：\n1. 完成核心功能的交互评审\n2. 确认分类整理与快速复制的操作' });
  await invoke('control_ui', { action: 'panel_open', value: 'clipboard-workbench/panel' }, 1000);
  let ui = await invoke('get_ui_state');
  let panel = ui.panel_instances.find(p => p.id === ui.active_panel);
  assert(panel, 'workbench must mount');
  let [px, py] = panel.bounds.split(',').map(Number);
  const click = async (x, y) => {
    for (const action of ['pointer_move', 'pointer_down', 'pointer_up']) await invoke('control_ui', { action, value: `${px + x},${py + y}` }, 250);
  };
  const state = () => invoke('get_clipboard_state');
  let current = await state();
  assert(current.items.every(item => !Object.hasOwn(item, 'content')));
  assert.equal(current.items.find(item => item.id === link.id).kind, 'link');
  assert.equal(current.items.find(item => item.id === code.id).kind, 'code');
  await step({ tool: 'get_clipboard_state', capture: 'clipboard-v2-initial' });
  await click(200, 530);
  await invoke('control_ui', { action: 'input_text', value: '工作' }, 500);
  current = await state();
  assert.equal(current.ui.category_name_length, 2, 'real GPUI input must receive the group name');
  await step({ tool: 'get_clipboard_state', capture: 'clipboard-v2-group-form' });
  await click(80, 615);
  current = await state();
  const group = current.categories.find(group => group.name === '工作');
  assert(group, 'group created by the UI must persist');
  await click(990, 468);
  await step({ tool: 'get_clipboard_state', capture: 'clipboard-v2-group-menu' });
  await click(990, 528);
  current = await state();
  assert.equal(current.items.find(item => item.id === first.id).category_id, group.id, 'group choice must save immediately without saving the text');
  await click(80, 570);
  current = await state();
  assert.equal(current.ui.filter, `group:${group.id}`);
  assert.deepEqual(current.ui.visible_ids, [first.id]);
  await step({ tool: 'get_clipboard_state', capture: 'clipboard-v2-group-filter' });
  await click(80, 426);
  assert.deepEqual((await state()).ui.visible_ids, [link.id], 'link type filter should use automatic detection');
  await click(80, 470);
  assert.deepEqual((await state()).ui.visible_ids, [code.id], 'code type filter should use automatic detection');
  await click(80, 285);
  current = await state();
  assert(!current.ui.visible_ids.includes(first.id), 'unclassified excludes grouped items');
  await click(80, 200);
  await invoke('control_ui', { action: 'panel_close', value: panel.id }, 500);
  await invoke('control_ui', { action: 'panel_open', value: 'clipboard-workbench/panel' }, 700);
  current = await state();
  assert.equal(current.items.find(item => item.id === first.id).category_id, group.id, 'assignment survives reopening the view');
  const revision = current.revision;
  await delay(1100);
  assert.equal((await state()).revision, revision, 'quiet state must not mutate revisions');
  await step({ tool: 'get_clipboard_state', capture: 'clipboard-v2-final' });
  ui = await invoke('get_ui_state');
  panel = ui.panel_instances.find(p => p.id === ui.active_panel);
  [px, py] = panel.bounds.split(',').map(Number);
  await click(110, 142);
  await invoke('control_ui', { action: 'input_text', value: 'EcoPaste' }, 400);
  assert.deepEqual((await state()).ui.visible_ids, [link.id], 'search filters the actual history');
  assert.equal((await state()).ui.selected, link.id, 'search inspector must follow its visible result');
  await invoke('control_ui', { action: 'key_press', value: 'ctrl-a' }, 200);
  await invoke('control_ui', { action: 'key_press', value: 'backspace' }, 300);
  assert.equal((await state()).ui.visible_ids.length, 4, 'clearing search restores history');
  await click(80, 570);
  await click(70, 625);
  await invoke('control_ui', { action: 'key_press', value: 'ctrl-a' }, 200);
  await invoke('control_ui', { action: 'input_text', value: '项目' }, 400);
  assert.equal((await state()).ui.category_name_length, 2);
  await click(80, 615);
  assert.equal((await state()).categories.find(item => item.id === group.id).name, '项目', 'rename preserves group identity');
  await click(160, 625);
  await step({ tool: 'get_clipboard_state', capture: 'clipboard-v2-delete-confirm' });
  await click(80, 615);
  current = await state();
  assert(!current.categories.some(item => item.id === group.id), 'delete removes the group');
  assert.equal(current.items.length, 4, 'delete group keeps history');
  assert.equal(current.items.find(item => item.id === first.id).category_id, null, 'deleted group entries become unclassified');
  await click(200, 693);
  assert.equal((await state()).capture_paused, true);
  await click(200, 693);
  assert.equal((await state()).capture_paused, false);
  await step({ tool: 'get_clipboard_state', capture: 'clipboard-v2-category-deleted' });
};
