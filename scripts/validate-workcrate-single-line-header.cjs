const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const net = require('node:net');
module.exports = async ({call,payload,step,delay,profile,root}) => {
  const invoke=async(tool,args={},extra={})=>(await step({tool,arguments:args,wait_ms:100,...extra})).result;
  const read=async(ids=[])=>payload(await call('workcrate-ui.state',{control_ids:ids}));
  const until=async(test,label,ids=[])=>{let s;for(let i=0;i<100;i++){s=await read(ids);if(test(s))return s;await delay(150);}await invoke('workcrate-ui.state',{}, {capture:'failed-state'});throw Error(`${label}: ${JSON.stringify(s)}`);};
  const ui=async(action,value)=>{
    for(let i=0;i<30;i++){try{return await invoke('control_ui',{action,value});}catch(e){if(!String(e).includes('still pending'))throw e;await delay(150);}}
    throw Error('UI queue busy');
  };
  const click=async id=>{const s=await until(s=>s.controls[id],id,[id]);const[x,y,w,h]=s.controls[id].split(',').map(Number);await ui('pointer_down',`${x+w/2},${y+h/2}`);await ui('pointer_up',`${x+w/2},${y+h/2}`);};
  const draft=async(key,text)=>{await click(`field-${key}`);await click('field-edit-input');await ui('key_press','ctrl-a');await ui(text?'input_text':'key_press',text||'backspace');await ui('key_press','enter');return until(s=>!s.ui.field_saves.length&&!s.ui.editing&&/^已保存/.test(s.ui.message||''),'field saved');};
  const header=()=>invoke('workcrate-ui.header_state');
  const stable=(next,base)=>{
    assert.deepEqual(Object.fromEntries(Object.entries(next.nodes).map(([k,n])=>[k,n.id])),Object.fromEntries(Object.entries(base.nodes).map(([k,n])=>[k,n.id])));
    assert.deepEqual(next.furniture,base.furniture,'background, chip and groups stay identical');
    assert.equal(next.last_write.report.initialized,false);
    const commands=next.last_write.report.commands.map(c=>c.command);
    assert.ok(!commands.some(c=>/create|rectangle|transform|move|group$|clear|setStyle|object\.setProps/.test(c)),commands.join(','));
  };
  const edited=(state,id)=>assert.deepEqual(state.last_write.report.commands.filter(c=>c.command==='text.setText').map(c=>c.id),[id]);
  const port=await new Promise(resolve=>{const s=net.createServer();s.listen(0,'127.0.0.1',()=>{const p=s.address().port;s.close(()=>resolve(p));});});
  const documents=path.join(profile,'documents');fs.mkdirSync(documents,{recursive:true});
  await invoke('workcrate-ui.configure_vectorcraft',{executable:'C:\\Program Files\\VectorCraft\\vectorcraft.exe',port});
  const created=await invoke('workcrate-ui.manage_project',{action:'create',name:`单行物料栏${Date.now()}`,directory:documents});
  const project=created.project.id,board=created.boards[0].id;
  await invoke('workcrate-ui.create_page',{project_id:project});
  await invoke('workcrate-ui.open_board',{project_id:project,board_id:board});
  await until(s=>s.ui?.canvas?.state?.board_id===board&&!s.ui.canvas.busy&&!s.ui.busy&&s.ui.previews_ready===2,'editor');
  const base=await header();assert.equal(base.layout,2);assert.deepEqual(Object.keys(base.nodes),['details','page_number','project_name']);
  await draft('local','会场物料');
  const category=await header();stable(category,base);edited(category,base.nodes.project_name.id);
  assert.deepEqual(category.nodes.details,base.nodes.details);
  await draft('material','人物立牌');
  const material=await header();stable(material,category);edited(material,base.nodes.details.id);
  assert.deepEqual(material.nodes.project_name,category.nodes.project_name);
  const start=await read();
  await invoke('workcrate-ui.update_page',{project_id:project,board_id:board,info:{size:'20 × 30 cm',quantity:'2 套',extra:{工艺:'UV | 覆膜',备注:'户内\n使用'}}});
  await until(s=>s.ui.boards.find(b=>b.id===board).info.quantity==='2 套'&&!s.ui.canvas.busy,'aggregate patch');
  const details=await header();stable(details,material);edited(details,base.nodes.details.id);
  assert.deepEqual(details.nodes.project_name,category.nodes.project_name);
  assert.equal(details.nodes.details.text,'人物立牌 | 20 × 30 cm | 2 套 | 户内 使用 | UV | 覆膜');
  const rect=n=>n.summary.bounds;
  assert.ok(Math.abs(rect(details.nodes.details).x+rect(details.nodes.details).width-(rect(material.nodes.details).x+rect(material.nodes.details).width))<0.1,'right anchor fixed');
  assert.ok(Math.abs(rect(details.nodes.details).height-rect(material.nodes.details).height)<0.1,'one line');
  assert.equal((await read()).ui.reloads,start.ui.reloads);
  await invoke('workcrate-ui.state',{}, {capture:'single-line-complete'});
  await invoke('workcrate-ui.update_page',{project_id:project,board_id:board,info:{extra:{工艺:'UV | 覆膜',备注:'户内\n使用',空字段:''}}});
  const empty=await header();stable(empty,details);assert.equal(empty.last_write.report.commands.filter(c=>c.command==='text.setText').length,0);
  await step({tool:'workcrate-ui.update_page',arguments:{project_id:project,board_id:board,info:{material:'超长'.repeat(200)}},expect_error:'单行放不下'});
  const refused=await header();assert.deepEqual(refused.nodes,empty.nodes,'overflow rollback preserves every native node');
  await until(s=>!s.ui.canvas.busy&&!s.ui.busy,'idle before overflow draft');
  await click('field-material');await until(s=>s.ui.editing===`${board}#material`,'overflow draft opened');await click('field-edit-input');await ui('key_press','ctrl-a');await ui('input_text','超'.repeat(80));await click('field-edit-save');
  await until(s=>!s.ui.field_saves.length&&/保存失败/.test(s.ui.message||'')&&s.ui.editing===`${board}#material`,'overflow keeps the draft');
  await invoke('workcrate-ui.state',{}, {capture:'single-line-overflow'});
  await click('field-edit-cancel');
  await step({tool:'workcrate-ui.update_page',arguments:{project_id:project,board_id:board,info:{size_label:'A3 横向'}},expect_error:'仅支持修改物料内容'});
  const unchanged=await header();assert.deepEqual(unchanged.nodes,empty.nodes);

  await draft('local','');
  const cleared=await header();stable(cleared,empty);edited(cleared,base.nodes.project_name.id);
  await invoke('workcrate-ui.state',{}, {capture:'single-line-cleared-category'});
  await invoke('workcrate-ui.navigate',{project_id:project});
  await invoke('workcrate-ui.refresh_project',{project_id:project});
  await invoke('workcrate-ui.open_board',{project_id:project,board_id:board});
  await until(s=>s.ui?.canvas?.state?.board_id===board&&!s.ui.canvas.busy&&!s.ui.busy,'reopened');
  const reopened=await read();const saved=reopened.ui.boards.find(b=>b.id===board).info;
  assert.equal(saved.material_category,'');assert.equal(saved.extra.工艺,'UV | 覆膜');assert.equal(saved.extra.备注,'户内\n使用');assert.equal(saved.extra.空字段,'');
  const again=await header();assert.equal(again.nodes.details.id,base.nodes.details.id);
  await draft('quantity','3 套');const resumed=await header();stable(resumed,again);edited(resumed,base.nodes.details.id);
  const legacySource=path.join(root,'.local/validation/profiles/wc-defaults-2026-10-23-v3/documents/默认信息测试A.vectorcraft');
  let migration=false;
  if(fs.existsSync(legacySource)){
    await invoke('workcrate-ui.navigate',{project_id:project});
    const legacy=path.join(documents,'legacy.vectorcraft');fs.copyFileSync(legacySource,legacy);
    await invoke('workcrate-ui.attach_document',{project_id:project,path:legacy});
    const refreshed=await invoke('workcrate-ui.refresh_project',{project_id:project});
    const oldBoard=refreshed.boards[0].id;
    await invoke('workcrate-ui.open_board',{project_id:project,board_id:oldBoard});
    await until(s=>s.ui?.canvas?.state?.board_id===oldBoard&&!s.ui.canvas.busy&&!s.ui.busy,'legacy editor');
    const old=await header();assert.equal(old.layout,0);
    await draft('material','旧版迁移物料');
    const migrated=await header();assert.equal(migrated.layout,2);assert.equal(migrated.last_write.report.initialized,true);assert.equal(migrated.nodes.project_name.note.value,'活动展示');
    await draft('quantity','1 套');const patched=await header();stable(patched,migrated);edited(patched,migrated.nodes.details.id);
    await invoke('workcrate-ui.state',{}, {capture:'single-line-migrated'});
    migration=true;
  }
  await invoke('resize_window',{width:1600,height:1100});
  await invoke('workcrate-ui.state',{}, {capture:'single-line-small-window'});
  await invoke('resize_window',{width:3286,height:1831});
  await delay(1000);const quiet=await read();await delay(3500);const idle=await read();assert.equal(idle.ui.reloads,quiet.ui.reloads);
  fs.writeFileSync(path.join(profile,'single-line-summary.json'),JSON.stringify({passed:true,project,board,migration,checks:['three stable text ids','category-only writes','one aggregate text update','stable background/chip/groups','fixed right anchor/one line','structured separator/newline/empty roundtrip','overflow rollback','native reopen and subsequent patch',...(migration?['legacy one-time migration']:[]),'quiet catalogue']},null,2));
};
