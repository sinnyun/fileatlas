const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),net=require('node:net');
const {execFileSync}=require('node:child_process');
const {createHash}=require('node:crypto');
const hash=file=>createHash('sha256').update(fs.readFileSync(file)).digest('hex');
module.exports=async({step,call,payload,delay,profile})=>{
  const invoke=async(tool,args={},extra={})=>(await step({tool,arguments:args,wait_ms:150,...extra})).result;
  const read=async(ids=[])=>payload(await call('workcrate-ui.state',{control_ids:ids}));
  const until=async(test,label,ids=[])=>{let s;for(let i=0;i<150;i++){s=await read(ids);if(s?.ui&&test(s))return s;await delay(150);}throw Error(`${label}: ${JSON.stringify(s)}`);};
  const click=async id=>{const s=await until(s=>s.controls[id],id,[id]);const[x,y,w,h]=s.controls[id].split(',').map(Number);for(const action of ['pointer_down','pointer_up'])await invoke('control_ui',{action,value:`${x+w/2},${y+h/2}`});};
  const original=path.join(profile,'documents','原项目');fs.mkdirSync(path.join(original,'images'),{recursive:true});
  const image=path.join(original,'images','源图.png');
  const draw=(file,color)=>execFileSync('python',['-c','import sys; from PIL import Image,ImageDraw; im=Image.new("RGB",(240,160),sys.argv[2]); ImageDraw.Draw(im).rectangle((30,30,210,130),outline="white",width=8); im.save(sys.argv[1])',file,color]);
  draw(image,'#2563eb');
  const port=await new Promise(resolve=>{const s=net.createServer();s.listen(0,'127.0.0.1',()=>{const p=s.address().port;s.close(()=>resolve(p));});});
  const configure=executable=>invoke('workcrate-ui.configure_vectorcraft',{executable,port});
  await configure('C:\\Program Files\\VectorCraft\\vectorcraft.exe');
  const created=await invoke('workcrate-ui.manage_project',{action:'create',name:'随文件保存的项目',directory:original});
  const project_id=created.project.id,A=created.boards[0].id;
  const data=path.join(original,'.workcrate',project_id),manifest=path.join(data,'project.json');
  assert.ok(fs.existsSync(manifest),'creation must immediately create adjacent metadata');
  const initial=JSON.parse(fs.readFileSync(manifest));assert.equal(initial.portable,true);assert.ok(!path.isAbsolute(initial.native_document));
  const native=path.join(original,initial.native_document);
  const B=(await invoke('workcrate-ui.create_page',{project_id})).board_id;
  await invoke('workcrate-ui.update_page',{project_id,board_id:A,info:{material_category:'分类甲',material:'随项目物料',quantity:'3',extra:{工艺:'覆膜'}}});
  const presets={version:1,fields:[{key:'local',label:'物料类别',values:['便携类别']},{key:'material',label:'物料名称',values:['便携默认物料']},{key:'size',label:'尺寸',values:[]},{key:'quantity',label:'数量',values:['3']}]};
  await invoke('workcrate-ui.field_presets',{project_id,presets});
  await invoke('workcrate-ui.manage_project',{action:'cover',project_id,path:image});
  await invoke('workcrate-ui.canvas_open',{board_id:A});
  await invoke('workcrate-ui.canvas_place',{path:image,at:[500,350],link:true,confirm:true});
  const linked=await invoke('workcrate-ui.header_state');assert.equal(linked.links.links.length,1);assert.equal(linked.links.links[0].status,'ok');
  const imageId=linked.links.links[0].id;
  await invoke('workcrate-ui.canvas_close',{project_id});
  await invoke('workcrate-ui.navigate',{});await until(s=>s.ui.screen==='projects'&&!s.ui.busy,'project overview');
  await click(`project-menu-${project_id}`);
  await invoke('workcrate-ui.state',{control_ids:[`project-relocate-${project_id}`,'workcrate-open-project-folder']},{capture:'portable-project-menu'});
  const nativeHash=hash(native),imageHash=hash(image);
  await configure(path.join(profile,'no-vectorcraft.exe'));
  await click(`project-relocate-${project_id}`);await until(s=>!s.ui.busy&&!s.ui.canvas.busy,'idempotent metadata migration');
  assert.equal(hash(native),nativeHash);assert.equal(hash(image),imageHash);
  const migrated=JSON.parse(fs.readFileSync(manifest));assert.equal(migrated.references[0].path,'images/源图.png');
  assert.ok(fs.existsSync(path.join(data,'boards-cache.json')));
  assert.ok(migrated.project.main_image);assert.ok(fs.existsSync(path.join(data,migrated.project.main_image.path)));
  const moved=path.join(profile,'moved','改名后的项目');fs.mkdirSync(path.dirname(moved),{recursive:true});
  fs.renameSync(original,moved);
  const recovered=await invoke('workcrate-ui.project_folder',{action:'open',folder:moved});
  assert.equal(recovered.projects[0].id,project_id);
  const location=await invoke('workcrate-ui.project_folder',{action:'inspect',project_id});
  assert.ok(location.document.endsWith(initial.native_document));assert.ok(location.references[0].path.includes('改名后的项目'));
  const saved=await invoke('workcrate-ui.state',{project_id});assert.deepEqual(saved.project_presets,presets);
  await invoke('workcrate-ui.navigate',{project_id});
  const pages=await until(s=>s.ui.project_id===project_id&&s.ui.page_count===2&&!s.ui.busy,'cached pages');
  assert.deepEqual(pages.ui.boards.map(b=>b.id),[A,B]);
  assert.equal(pages.ui.boards[0].info.material,'随项目物料');
  await invoke('workcrate-ui.state',{}, {capture:'portable-recovered-pages'});
  assert.equal(hash(path.join(moved,initial.native_document)),nativeHash,'recovery with missing CLI never modifies native file');
  await configure('C:\\Program Files\\VectorCraft\\vectorcraft.exe');
  await invoke('workcrate-ui.canvas_open',{board_id:A});
  const reopened=await invoke('workcrate-ui.header_state');
  assert.equal(reopened.links.links[0].id,imageId);assert.equal(reopened.links.links[0].status,'ok');
  const movedImage=path.join(moved,'images','源图.png');draw(movedImage,'#dc2626');
  const updated=await invoke('workcrate-ui.canvas_links',{action:'update',ids:[imageId],confirm:true});
  assert.ok(updated.canvas.preview);
  await invoke('workcrate-ui.open_board',{project_id,board_id:A});await until(s=>s.ui.board_id===A&&!s.ui.busy&&!s.ui.canvas.busy,'restored editor');
  await invoke('workcrate-ui.state',{}, {capture:'portable-link-updated'});
  // Move while a session still knows the old location: recovery must not recreate it.
  const movedAgain=path.join(profile,'moved','再次改名');fs.renameSync(moved,movedAgain);
  await invoke('workcrate-ui.project_folder',{action:'open',folder:movedAgain});
  assert.ok(!fs.existsSync(moved));
  await invoke('workcrate-ui.canvas_open',{board_id:A});
  assert.equal((await invoke('workcrate-ui.header_state')).links.links[0].status,'ok');
  await invoke('workcrate-ui.canvas_close',{project_id});
  await invoke('workcrate-ui.manage_project',{action:'rename',project_id,name:'移动后重命名'});
  const latest=JSON.parse(fs.readFileSync(path.join(movedAgain,'.workcrate',project_id,'project.json')));
  assert.equal(latest.project.name,'移动后重命名');assert.equal(latest.native_binding,initial.native_binding);
  assert.equal(latest.references[0].path,'images/源图.png');
  await invoke('workcrate-ui.navigate',{});await until(s=>s.ui.screen==='projects'&&!s.ui.busy,'final overview');
  await invoke('resize_window',{width:1600,height:1100});await invoke('workcrate-ui.state',{}, {capture:'portable-small-window'});
  const quiet=await read();await delay(3500);assert.equal((await read()).ui.reloads,quiet.ui.reloads);
  fs.writeFileSync(path.join(profile,'portable-summary.json'),JSON.stringify({project_id,A,B,folder:movedAgain,imageId,checks:['adjacent metadata at create','project presets and cover','original native links','no CLI for metadata migration/recovery','native hash unchanged','folder move/rename with cached preview','native link update','active session folder move without stale save','project rename persisted beside native','small window','quiet state']},null,2));
};
