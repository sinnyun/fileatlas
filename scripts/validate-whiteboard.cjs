// Native upstream input and host persistence through FileAtlas's same-process MCP.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
module.exports = async ({ call, payload, delay, step, profile, root }) => {
  const invoke = async (name, args = {}) => payload(await call(name, args));
  const input = async (action, value) => { await invoke('control_ui', { action, value }); await delay(180); };
  const click = async (x, y) => { await input('pointer_move', `${x},${y}`); await input('pointer_down', `${x},${y}`); await input('pointer_up', `${x},${y}`); };
  const drag = async (x1,y1,x2,y2) => { await input('pointer_move',`${x1},${y1}`); await input('pointer_down',`${x1},${y1}`); await input('pointer_drag',`${x2},${y2}`); await input('pointer_up',`${x2},${y2}`); };
  const key = value => input(value.length===1?'input_text':'key_press',value);
  const state = () => invoke('whiteboard.state');
  const scene = async id => JSON.parse((await state()).library.boards.find(b => b.id===id).scene);
  const wait = async fn => { for(let i=0;i<40;i++){ if(await fn())return; await delay(150); } throw Error('whiteboard state did not settle'); };
  const { id } = await invoke('whiteboard.create',{title:'MCP Native Whiteboard'});
  await delay(800);
  const ui = await invoke('get_ui_state');
  const panel = ui.panel_instances.find(p=>p.id.startsWith('whiteboard/panel@'));
  assert(panel, 'managed floating panel must mount');
  const [x,y] = panel.client_bounds.split(',').map(Number);
  await step({tool:'screenshot_window',capture:'whiteboard-empty'});
  // Click upstream's Select toolbar button first: Pan mode itself need not focus keys.
  await click(x+532,y+111);
  await key('r');
  await drag(x+360,y+250,x+600,y+400);
  await step({tool:'screenshot_window',capture:'whiteboard-rectangle'});
  await wait(async()=> (await scene(id)).elements.some(e=>e.kind.rect));
  const rectangle=(await scene(id)).elements.find(e=>e.kind.rect);
  await key('ctrl-z');
  await wait(async()=>!(await scene(id)).elements.some(e=>e.kind.rect));
  await key('ctrl-shift-z');
  await wait(async()=> (await scene(id)).elements.some(e=>e.kind.rect));
  await key('v');
  await drag(x+450,y+320,x+510,y+360);
  const moved=(await scene(id)).elements.find(e=>e.id===rectangle.id);
  assert(moved.kind.rect.x>rectangle.kind.rect.x,'native selection drag must move native geometry');
  await key('t');
  await click(x+760,y+300);
  await input('input_text','Zorite native board');
  await key('escape');
  await wait(async()=> (await scene(id)).elements.some(e=>e.kind.text?.content==='Zorite native board'));
  const fixture=path.join(profile,'linked-image.png');
  fs.copyFileSync(path.join(root,'test-data/fileatlas-fixtures/01-small/small.png'),fixture);
  const hash=()=>crypto.createHash('sha256').update(fs.readFileSync(fixture)).digest('hex');
  const before=hash();
  await invoke('whiteboard.add_images',{id,paths:[fixture],at:[730,440]});
  await wait(async()=> (await scene(id)).elements.some(e=>e.kind.image));
  await delay(800);
  await step({tool:'screenshot_window',capture:'whiteboard-image-text'});
  assert.equal(hash(),before,'linked image bytes must remain unchanged');
  await key('v');
  await click(x+300,y+520); // clear selection without closing the host panel via Escape
  assert((await invoke('get_ui_state')).open_panel_ids.some(id=>id.startsWith('whiteboard/panel@')),'quiet-state check requires a mounted board');
  await invoke('whiteboard.flush');
  const saved=await state();
  assert.equal(saved.save.error,null);
  assert.equal(saved.save.revision,saved.save.saved_revision);
  const mtime=fs.statSync(saved.path).mtimeMs;
  await delay(1300);
  const quiet=await state();
  assert.equal(quiet.save.revision,saved.save.revision,'settled board must not mutate');
  assert.equal(fs.statSync(saved.path).mtimeMs,mtime,'settled board must not rewrite library');
  assert((await invoke('get_ui_state')).open_panel_ids.some(id=>id.startsWith('whiteboard/panel@')),'board must stay mounted while idle');
  const output=path.join(profile,'native-export.json');
  await invoke('whiteboard.export',{id,path:output,confirm:true});
  const exported=JSON.parse(fs.readFileSync(output,'utf8'));
  assert.deepEqual(exported,await scene(id));
  const imported=await invoke('whiteboard.import',{path:output});
  await delay(600);
  assert.deepEqual(await scene(imported.id),exported);
  await invoke('whiteboard.rename',{id:imported.id,title:'Imported Native Whiteboard'});
  await invoke('whiteboard.open',{id});
  await delay(500);
  await invoke('whiteboard.flush');
  await step({tool:'screenshot_window',capture:'whiteboard-final'});
  const current=(await invoke('get_ui_state')).panel_instances.find(p=>p.id.startsWith('whiteboard/panel@'));
  const [left,top,width,height]=current.bounds.split(',').map(Number);
  await drag(left+width-2,top+height-2,left+width-452,top+height-252);
  await delay(400);
  await step({tool:'screenshot_window',capture:'whiteboard-small'});
  const small=(await invoke('get_ui_state')).panel_instances.find(p=>p.id===current.id);
  assert(Number(small.bounds.split(',')[2])<900,'generic floating panel must resize to a small layout');
  fs.writeFileSync(path.join(profile,'whiteboard-result.json'),JSON.stringify({id,imported_id:imported.id,scene:await scene(id),panel,small,cases:['native rectangle pointer creation','native undo/redo','native selection movement','native text input','host linked-image placement','unchanged source image','native JSON export/import','quiet revisions and file mtime','host board switching and rename','small floating panel']},null,2));
  console.log(JSON.stringify({passed:true,id,imported_id:imported.id,profile}));
  fs.copyFileSync(path.join(profile,'report.json'),path.join(profile,'whiteboard-main-report.json'));
};
