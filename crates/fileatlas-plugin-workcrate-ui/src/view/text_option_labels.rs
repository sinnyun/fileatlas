pub(super) fn choices(key: &str, current: &serde_json::Value) -> Vec<String> {
    if current.is_boolean() {
        return vec!["true".into(), "false".into()];
    }
    let values: &[&str] = match key {
        "align" => &[
            "left",
            "center",
            "right",
            "leftJustified",
            "centerJustified",
            "rightJustified",
            "fullyJustified",
            "towardsSpine",
            "awayFromSpine",
        ],
        "direction" => &["leftToRight", "rightToLeft"],
        "position" => &["normal", "superscript", "subscript"],
        "capitalization" => &["normal", "allCaps", "smallCaps"],
        "listType" => &["none", "bullets", "numbers"],
        "verticalJustification" => &["top", "center", "bottom", "justify"],
        "firstBaseline" => &[
            "ascent",
            "capHeight",
            "leading",
            "xHeight",
            "fixed",
            "emboxHeight",
        ],
        "autoSize" => &[
            "off",
            "heightOnly",
            "widthOnly",
            "heightAndWidth",
            "heightAndWidthProportionally",
        ],
        "columnsKind" => &["fixedNumber", "fixedWidth", "flexibleWidth"],
        "fontStyle" => &["Regular", "Bold", "Italic", "Bold Italic"],
        "leading" => &[r#"{"kind":"auto"}"#, r#"{"kind":"points","value":28}"#],
        "kerning" => &[
            r#"{"kind":"metrics"}"#,
            r#"{"kind":"optical"}"#,
            r#"{"kind":"none"}"#,
            r#"{"kind":"manual","value":0}"#,
        ],
        "digits" => &["default", "arabic", "hindi", "farsi", "native"],
        "language" => &[
            "Chinese: Simplified",
            "Chinese: Traditional",
            "English: USA",
            "Japanese",
            "Korean",
            "[No Language]",
        ],
        _ => &[],
    };
    values.iter().map(|v| v.to_string()).collect()
}
